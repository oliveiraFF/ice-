const assert = require('node:assert/strict');
const picker = require('../static/capture-picker.js');
const china = {id:'POST /api/v1/douyin/search/fetch_video_search_v2',platform:'douyin',platform_name:'抖音',title:'视频搜索',path:'/api/v1/douyin/search/fetch_video_search_v2',collection_supported:true};
const foreign = {id:'GET /api/v1/youtube/web/search_video',platform:'youtube',platform_name:'YouTube',title:'搜索视频',path:'/api/v1/youtube/web/search_video',collection_supported:false};
assert.equal(picker.regionOf('douyin'), 'domestic');
assert.equal(picker.regionOf('youtube'), 'overseas');
assert.equal(picker.regionOf('unrecognized'), 'other');
assert.deepEqual(picker.filter([china,foreign], 'overseas', 'youtube', 'SEARCH_VIDEO'), [foreign]);
assert.deepEqual(picker.filter([china,foreign], 'domestic', 'douyin', '不存在'), []);
let target = new URL(picker.parameterURL(foreign, 'AI 工具', [china.id,foreign.id]), 'http://localhost');
assert.equal(target.pathname, '/market');
assert.equal(target.searchParams.get('id'), foreign.id);
assert.equal(target.searchParams.get('collect'), '0');
assert.deepEqual(target.searchParams.getAll('pick'), [china.id,foreign.id]);
target = new URL(picker.parameterURL(china, '', [china.id]), 'http://localhost');
assert.equal(target.searchParams.get('collect'), '1');
assert.equal(target.searchParams.has('keyword'), false);
assert.deepEqual(picker.validSelection(['unknown',china.id,china.id,foreign.id], [china,foreign]), [china.id,foreign.id]);
assert.equal(picker.statusOf({documented:false,runnable:false}), '待接入');
assert.equal(picker.statusOf({documented:true,runnable:true,availability_label:'待验证'}), '未启用 · 待验证');
assert.deepEqual(picker.keywordTarget({path:'/search_video',parameters:[{in:'query',name:'search_query',schema:{type:'string'}}]}),{scope:'query',name:'search_query'});
assert.deepEqual(picker.keywordTarget({path:'/search',body_schema:{properties:{keyword:{type:'string'}}}}),{scope:'body',name:'keyword'});
assert.deepEqual(picker.keywordTarget({path:'/search',body_schema:{properties:{q:{anyOf:[{type:'null'},{type:'string'}]}}}}),{scope:'body',name:'q'});
assert.equal(picker.keywordTarget({path:'/search',body_schema:{properties:{query:{type:'object'}}}}),null);
assert.equal(picker.keywordTarget({path:'/graphql',parameters:[{in:'query',name:'query',schema:{type:'string'}}]}),null);
assert.equal(picker.keywordTarget({path:'/fetch_post_by_url',parameters:[{in:'query',name:'post_url',schema:{type:'string'}}]}),null);
assert.equal(picker.isLinkDetail({path:'/fetch_video_high_quality_play_url'}),false);
assert.equal(picker.isLinkDetail({path:'/fetch_post_by_url'}),true);
console.log('capture picker contracts passed');
